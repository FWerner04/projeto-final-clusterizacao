def br(x, casas=0):
    t = f"{x:,.{casas}f}"
    t = t.replace(",", "§").replace(".", ",").replace("§", ".")
    return t.replace("-", "−")


def eixo_br(ax, eixo="x", casas=0, sufixo=""):
    f = FuncFormatter(lambda v, _: br(v, casas) + sufixo)
    (ax.xaxis if eixo == "x" else ax.yaxis).set_major_formatter(f)


def rotular_barras(ax, barras, casas=0, sufixo="", dx=0, dy=3, horizontal=False, cor=None, tamanho=11, negrito=False):
    for b in barras:
        v = b.get_width() if horizontal else b.get_height()
        xy = (b.get_width(), b.get_y() + b.get_height() / 2) if horizontal else (b.get_x() + b.get_width() / 2, b.get_height())
        ax.annotate(br(v, casas) + sufixo, xy=xy, xytext=(dy if horizontal else dx, dx if horizontal else dy),
                    textcoords="offset points", ha="left" if horizontal else "center",
                    va="center" if horizontal else "bottom", fontsize=tamanho,
                    color=cor or TEMA["tinta"], fontweight="bold" if negrito else "normal")


